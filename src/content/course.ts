function exercise(
  id: string,
  theme: Theme,
  prompt: string,
  parts: [string, string][],
  explanation: string,
): Exercise {
  return {
    id: `sentence:${id}`,
    theme,
    prompt,
    thai: parts.map((p) => p[0]).join(""),
    roman: parts.map((p) => p[1]).join(" "),
    tiles: parts.map(([thai, roman], i) => ({
      id: `${id}-${i}`,
      token: thai,
      thai,
      roman,
    })),
    answers: [parts.map((p) => p[0])],
    explanation,
    review: "draft",
  };
}
